import { ApiProperty } from '@nestjs/swagger';

export class ChatResponseDto {
  @ApiProperty({
    description: 'The unique session ID associated with this conversation',
    example: '64a1b2c3d4e5f67890123456',
  })
  sessionId: string;

  @ApiProperty({
    description: 'The response generated by the club assistant',
    example:
      'General membership is 500 BDT/month, and the field opens daily at 6:00 AM.',
  })
  message: string;

  @ApiProperty({
    description: 'Message role',
    example: 'assistant',
  })
  role: 'assistant';
}
